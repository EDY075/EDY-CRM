test('envio com falha preserva texto na conversa recém-criada e permite recuperar',async({page})=>{
 await page.goto('/assistente')
 await page.getByLabel('Seu comando',{exact:true}).fill('Mostre os leads sem site')
 await page.route('**/assistente/conversas/*/mensagens',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({erro:'QA: conexão interrompida'})}))
 await page.getByRole('button',{name:'Executar comando',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('conexão interrompida')
 await expect(page.getByLabel('Seu comando',{exact:true})).toHaveValue('Mostre os leads sem site')
 await page.unroute('**/assistente/conversas/*/mensagens')
 await page.getByRole('button',{name:'Executar comando',exact:true}).click()
 await expect(page.getByLabel('Seu comando',{exact:true})).toHaveValue('')
 await expect(page.getByText('Comando reconhecido e colocado na fila.',{exact:false})).toBeVisible()
})

test('permissão negada não inicia transcrição e preserva rascunho',async({page})=>{
 // Falha de dispositivo simulada para contrato de UI; não prova microfone humano.
 await page.addInitScript(()=>Object.defineProperty(navigator.mediaDevices,'getUserMedia',{value:()=>Promise.reject(new DOMException('QA: microfone recusado','NotAllowedError'))}))
 await page.goto('/assistente');await page.getByLabel('Seu comando',{exact:true}).fill('Rascunho manual preservado')
 await page.getByRole('button',{name:'Gravar comando',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('Microfone bloqueado pelo navegador')
 await expect(page.getByLabel('Seu comando',{exact:true})).toHaveValue('Rascunho manual preservado')
 await expect(page.getByRole('button',{name:'Executar comando',exact:true})).toBeEnabled()
})

