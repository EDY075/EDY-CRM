import {test,expect} from '@playwright/test'
test('captura com dispositivo sintético de QA; ausência de credencial não simula transcrição',async({page,context})=>{
 await context.grantPermissions(['microphone'],{origin:'http://127.0.0.1:5129'})
 await page.goto('/assistente');await page.getByText('Preferências de voz',{exact:true}).click()
 await page.getByLabel('Transcrição',{exact:true}).selectOption('openai')
 await page.getByRole('button',{name:'Gravar comando'}).click()
 await expect(page.getByRole('button',{name:/Parar · 1s/})).toBeVisible()
 await page.getByRole('button',{name:/Parar ·/}).click()
 await page.getByText('Rever ou descartar áudio',{exact:true}).click()
 await expect(page.locator('audio')).toHaveCount(1)
 await expect(page.getByRole('alert')).toContainText('ED_CRM_VOICE_KEY')
 await expect(page.getByLabel('Seu comando')).toHaveValue('')
 await expect(page.locator('audio')).toHaveCount(1)
 await page.getByRole('button',{name:'Descartar captura'}).click();await expect(page.locator('audio')).toHaveCount(0)
})
